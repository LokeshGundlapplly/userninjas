import { Request, Response } from 'express';
import { supabaseAdmin } from '../config/database';
import { RazorpayService } from '../services/razorpay.service';
import { PaymentRepository } from '../repositories/payment.repository';
import { SubscriptionRepository } from '../repositories/subscription.repository';
import { ProfileRepository } from '../repositories/profile.repository';
import { EmailService } from '../services/email.service';
import { PLANS } from '../config/constants';
import { logger } from '../utils/logger';

const razorpayService = new RazorpayService();
const paymentRepo = new PaymentRepository();
const subRepo = new SubscriptionRepository();
const profileRepo = new ProfileRepository();
const emailService = new EmailService();

const WEBHOOK_SECRET = process.env.RAZORPAY_WEBHOOK_SECRET || 'userninjas_webhook_secret_2026';

export async function handleRazorpayWebhook(req: Request, res: Response) {
  try {
    const signature = req.headers['x-razorpay-signature'] as string;
    if (!signature) {
      logger.warn('Webhook request missing Razorpay signature header');
      return res.status(400).json({ error: 'Missing signature header' });
    }

    // Verify signature using the raw body
    // req.rawBody is generated by the express.json verify hook
    const rawBody = (req as any).rawBody ? (req as any).rawBody.toString() : JSON.stringify(req.body);
    const isVerified = razorpayService.verifyWebhookSignature(rawBody, signature, WEBHOOK_SECRET);

    if (!isVerified) {
      logger.error('Razorpay webhook signature verification failed!');
      return res.status(400).json({ error: 'Signature verification failed' });
    }

    const payload = req.body;
    const eventId = payload.id;
    const eventName = payload.event;

    logger.info(`Processing webhook event ${eventName} (ID: ${eventId})`);

    // Idempotency check: check if event was already processed
    const { data: existingLog, error: logErr } = await supabaseAdmin
      .from('webhook_logs')
      .select('*')
      .eq('event_id', eventId)
      .maybeSingle();

    if (existingLog && existingLog.processed) {
      logger.info(`Webhook event ${eventId} already processed. Skipping.`);
      return res.status(200).json({ received: true, duplicated: true });
    }

    // Insert log
    if (!existingLog) {
      await supabaseAdmin.from('webhook_logs').insert({
        event_id: eventId,
        event_name: eventName,
        payload,
        processed: false
      });
    }

    // Process event
    if (eventName === 'payment.captured') {
      const paymentEntity = payload.payload.payment.entity;
      const razorpayPaymentId = paymentEntity.id;
      const razorpayOrderId = paymentEntity.order_id;
      const amount = paymentEntity.amount / 100; // in rupees
      const currency = paymentEntity.currency;
      const userEmail = paymentEntity.email;
      const method = paymentEntity.method;

      // Look up associated order in DB
      const dbOrder = await paymentRepo.getOrderByRazorpayId(razorpayOrderId);
      const userId = dbOrder ? dbOrder.user_id : null;
      let targetUserId = userId;

      // If order not found in DB, try to match profile by email
      if (!targetUserId && userEmail) {
        const { data: profile } = await supabaseAdmin
          .from('profiles')
          .select('user_id')
          .eq('email', userEmail)
          .maybeSingle();
        if (profile) targetUserId = profile.user_id;
      }

      if (targetUserId) {
        // Update order status in database
        if (dbOrder) {
          await paymentRepo.updateOrderStatus(dbOrder.id, 'paid');
        }

        // Create Payment record
        await paymentRepo.createPaymentRecord({
          user_id: targetUserId,
          order_id: dbOrder ? dbOrder.id : null,
          gateway: 'razorpay',
          razorpay_payment_id: razorpayPaymentId,
          razorpay_signature: signature,
          amount,
          currency,
          status: 'successful',
          payment_method: method,
          captured: true,
          description: `Captured asynchronously via webhook event ${eventId}`
        });

        const planName = dbOrder ? dbOrder.plan_name : null;

        if (planName) {
          const planDetails = PLANS[planName];
          const startDate = new Date();
          const expiryDate = new Date();
          expiryDate.setDate(startDate.getDate() + (planDetails.days || 30));

          // Activate/upsert subscription
          await subRepo.upsertSubscription({
            user_id: targetUserId,
            plan_name: planName,
            status: 'active',
            start_date: startDate.toISOString(),
            expiry_date: expiryDate.toISOString(),
            cancel_at_period_end: false
          });

          // Update profiles limits
          await profileRepo.updateProfileSubscription(
            targetUserId,
            planName,
            planDetails.testLimit,
            expiryDate.toISOString()
          );

          // Send Email
          if (userEmail) {
            emailService.sendPaymentSuccess(userEmail, { amount, planName: planDetails.name, orderId: razorpayOrderId || eventId })
              .catch(err => logger.error('Webhook error sending payment success email:', err));
            emailService.sendSubscriptionActivated(userEmail, { planName: planDetails.name, expiryDate: expiryDate.toISOString() })
              .catch(err => logger.error('Webhook error sending activation email:', err));
          }
        } else {
          // Wallet Credits Top-up
          const { data: userProfile } = await supabaseAdmin.from('profiles').select('wallet_balance').eq('user_id', targetUserId).single();
          const currentBalance = userProfile?.wallet_balance || 0;
          await profileRepo.updateWalletBalance(targetUserId, currentBalance + amount);

          // Send Email
          if (userEmail) {
            emailService.sendPaymentSuccess(userEmail, { amount, planName: 'Wallet Credits Top-up', orderId: razorpayOrderId || eventId })
              .catch(err => logger.error('Webhook error sending payment success email:', err));
          }
        }
      } else {
        logger.warn(`Could not resolve user for webhook payment capture: ${razorpayPaymentId} / ${userEmail}`);
      }

    } else if (eventName === 'payment.failed') {
      const paymentEntity = payload.payload.payment.entity;
      const razorpayPaymentId = paymentEntity.id;
      const userEmail = paymentEntity.email;
      const amount = paymentEntity.amount / 100;
      const errorDescription = paymentEntity.error_description || 'Transaction declined';

      logger.warn(`Payment failed: ${razorpayPaymentId} - ${errorDescription}`);

      // Try to find user profile to send warning email
      if (userEmail) {
        emailService.sendPaymentFailed(userEmail, { amount, planName: 'Subscription Plan', errorReason: errorDescription })
          .catch(err => logger.error('Webhook error sending failed payment email:', err));
      }

    } else if (eventName === 'refund.processed') {
      const refundEntity = payload.payload.refund.entity;
      const paymentId = refundEntity.payment_id;
      const refundAmount = refundEntity.amount / 100;

      // Find original payment to update target user
      const { data: originalPayment } = await supabaseAdmin
        .from('payments')
        .select('*')
        .eq('razorpay_payment_id', paymentId)
        .maybeSingle();

      if (originalPayment) {
        // Create refund transaction
        await paymentRepo.createPaymentRecord({
          user_id: originalPayment.user_id,
          order_id: null,
          gateway: 'razorpay',
          razorpay_payment_id: refundEntity.id,
          razorpay_signature: `REFUND-${refundEntity.id}`,
          amount: refundAmount,
          currency: refundEntity.currency,
          status: 'refunded',
          payment_method: 'refund',
          captured: true,
          description: `Refund processed for payment ${paymentId}`
        });

        // Demote subscription
        await subRepo.updateSubscriptionStatus(originalPayment.user_id, 'refunded');
        await profileRepo.deactivateProfileSubscription(originalPayment.user_id);

        // Notify user
        const { data: profile } = await supabaseAdmin
          .from('profiles')
          .select('email')
          .eq('user_id', originalPayment.user_id)
          .maybeSingle();

        if (profile?.email) {
          emailService.sendRefundConfirmation(profile.email, { amount: refundAmount, paymentId })
            .catch(err => logger.error('Webhook error sending refund confirmation email:', err));
        }
      }
    }

    // Mark webhook log as processed
    await supabaseAdmin
      .from('webhook_logs')
      .update({ processed: true })
      .eq('event_id', eventId);

    return res.status(200).json({ received: true });
  } catch (error: any) {
    logger.error('Error handling Razorpay webhook:', error);
    return res.status(500).json({ error: error.message || 'Webhook internal failure' });
  }
}
